def real_pack(matrix):
    return np.concatenate([matrix.real.ravel(),matrix.imag.ravel()])

def real_unpack(vector,shape):
    size=int(np.prod(shape))
    return vector[:size].reshape(shape)+1j*vector[size:].reshape(shape)

def real_span(columns,tolerance=1e-9):
    if not columns:
        return np.zeros((0,0))
    matrix=np.stack(columns,axis=1)
    u,singular_values,_=np.linalg.svd(matrix,full_matrices=False)
    threshold=tolerance*max(1.0,float(singular_values[0]) if len(singular_values) else 1.0)
    return u[:,singular_values>threshold]

def krylov_closure(initial,actions,shape,tolerance=1e-9):
    basis=real_span([real_pack(item) for item in initial],tolerance)
    dimensions=[int(basis.shape[1])]
    while True:
        candidates=[]
        for column in range(basis.shape[1]):
            item=real_unpack(basis[:,column],shape)
            for action in actions:
                candidates.append(real_pack(action(item)))
        block=np.stack(candidates,axis=1)
        block-=basis@(basis.T@block)
        block-=basis@(basis.T@block)
        added=real_span([block[:,index] for index in range(block.shape[1])],tolerance)
        if added.shape[1]==0:
            break
        basis=np.concatenate([basis,added],axis=1)
        basis,_=np.linalg.qr(basis)
        dimensions.append(int(basis.shape[1]))
    return basis,dimensions

