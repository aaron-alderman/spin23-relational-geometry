#!/usr/bin/env node

import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(process.cwd());
const claimsRoot = join(root, "corpus", "claims");
const verificationRoot = join(root, "verification");

const claimRows = readdirSync(claimsRoot, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && /^\d{4}-\d{4}$/u.test(entry.name))
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(entry => {
    const files = readdirSync(join(claimsRoot, entry.name)).filter(name => /^\d+_.*\.md$/iu.test(name));
    const ids = files.map(name => Number(/^(\d+)_/u.exec(name)[1]));
    return `| [${entry.name}](${entry.name}/) | ${files.length} | ${Math.min(...ids)} | ${Math.max(...ids)} |`;
  });

const claimIndex = `# Claim-range index\n\nGenerated by \`tooling/indexing/generate_repository_indexes.mjs\`.\n\n| Range | Documents | First ID | Last ID |\n|---|---:|---:|---:|\n${claimRows.join("\n")}\n`;
writeFileSync(join(claimsRoot, "INDEX.md"), claimIndex);

const verificationRows = readdirSync(verificationRoot, { withFileTypes: true })
  .filter(entry => entry.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(entry => {
    const files = readdirSync(join(verificationRoot, entry.name)).filter(name => name.endsWith(".mjs"));
    return `| [${entry.name}](${entry.name}/) | ${files.length} |`;
  });

const verificationIndex = `# Certificate-operation index\n\nGenerated by \`tooling/indexing/generate_repository_indexes.mjs\`. Operation folders are navigational labels, not epistemic grades.\n\n| Operation | Certificates |\n|---|---:|\n${verificationRows.join("\n")}\n\n**Total certificates:** ${verificationRows.reduce((sum, row) => sum + Number(/\| (\d+) \|$/u.exec(row)[1]), 0)}\n`;
writeFileSync(join(verificationRoot, "INDEX.md"), verificationIndex);

console.log(JSON.stringify({ claimRanges: claimRows.length, verificationOperations: verificationRows.length }, null, 2));
