import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "../..");
const evidence = JSON.parse(await readFile(resolve(root, "evidence/data/zenodo-eis-frozen-two-tone-protocol-v1.json"), "utf8"));
assert.equal(evidence.protocol, "zenodo-eis-frozen-two-tone-protocol/1");
assert.deepEqual(evidence.frozenProtocol.calibrationFrequenciesHz, [10000, 2.82193493843079]);
assert.equal(evidence.frozenProtocol.neighbourCount, 3);
assert.equal(evidence.frozenProtocol.adaptiveChoicesPerTarget, 0);
assert.equal(evidence.population.passedCells, 54);
assert.equal(evidence.population.failedCells, 0);
assert.ok(evidence.population.worstCellMedianRelativeError < 0.05);
assert.ok(evidence.population.worstCellMaximumRelativeError < 0.2);
assert.equal(evidence.decision.deployableWithinBatchPointPredictionRuleEstablished, true);
assert.equal(evidence.decision.externalBatchReplicationEstablished, false);
assert.equal(evidence.decision.measurementCovarianceEstablished, false);
assert.equal(evidence.decision.generatedDynamicsEstablished, false);
assert.equal(evidence.decision.newPhysicsEvidence, false);
console.log(JSON.stringify({ result: "pass", cells: 54, tonesHz: evidence.frozenProtocol.calibrationFrequenciesHz, neighbours: 3, worstMedianError: evidence.population.worstCellMedianRelativeError, boundary: "frozen within-batch point prediction closed; joint uncertainty and external replication remain open" }, null, 2));
