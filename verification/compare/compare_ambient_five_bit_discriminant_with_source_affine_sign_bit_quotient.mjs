import assert from 'node:assert/strict';

const dot=(x,y)=>x.reduce((s,a,i)=>s+a*y[i],0);
const gram=cols=>cols.map(x=>cols.map(y=>dot(x,y)));
const det=A=>A.length===1?A[0][0]:A[0].reduce((s,x,j)=>s+(j%2?-1:1)*x*det(A.slice(1).map(r=>r.filter((_,k)=>k!==j))),0);
const mod=(n,m)=>((n%m)+m)%m;

// Sixteen even-parity five-bit SO(10) spinor weights.
const points=[];
for(let n=0;n<32;n++){
  const b=Array.from({length:5},(_,i)=>(n>>i)&1);
  if(b.reduce((s,x)=>s+x,0)%2===0)points.push(b);
}
assert.equal(points.length,16);
const F=Array(16).fill(1);
const bits=Array.from({length:5},(_,i)=>points.map(b=>b[i]));
const signs=bits.map(b=>b.map(x=>1-2*x));

// Source charge lattice L_Q=<F,q1,...,q5>.
const GQ=gram([F,...signs]);
assert.deepEqual(GQ,[
  [16,0,0,0,0,0],
  [0,16,0,0,0,0],
  [0,0,16,0,0,0],
  [0,0,0,16,0,0],
  [0,0,0,0,16,0],
  [0,0,0,0,0,16],
]);

// Affine sign-bit lattice B=<F,b1,...,b5>.
const GB=gram([F,...bits]);
assert.equal(Math.abs(det(GQ))/Math.abs(det(GB)),32*32);
assert(GB.every((row,i)=>row.every((x,j)=>i!==j||x%2===0)));

// B/L_Q is (Z2)^5, generated by the b_i classes.  Every combination
// has integral q=(x,x)/2 and integral mutual pairing, so the gluing
// subgroup is totally isotropic in A_LQ.
const reps=[];
for(let n=0;n<32;n++){
  const x=Array(16).fill(0);
  for(let i=0;i<5;i++)if((n>>i)&1)for(let j=0;j<16;j++)x[j]+=bits[i][j];
  reps.push(x);
  assert.equal(mod(dot(x,x),2),0);
  assert.equal(mod(dot(x,x)/2,1),0);
}
for(const x of reps)for(const y of reps)assert.equal(mod(dot(x,y),1),0);

// New ambient-intersection shell q4=2ab+3c+2de is nontrivial and nondegenerate.
const dist={};
for(let n=0;n<32;n++){
  const [a,b,c,d,e]=Array.from({length:5},(_,i)=>(n>>i)&1);
  const q4=mod(2*a*b+3*c+2*d*e,4);
  dist[q4]=(dist[q4]??0)+1;
}
assert.deepEqual(dist,{0:10,1:6,2:6,3:10});
assert.notEqual(dist[0],32);

console.log('ambient_five_bit_vs_source_sign_bit_quadratic_comparison: PASS');
console.log('source_affine_sign_bit_quotient_is_F2_to_the_5_of_order32');
console.log('source_quotient_is_a_totally_isotropic_glue_subgroup_for_the_natural_16_field_pairing');
console.log('source_induced_quadratic_form_is_identically_zero');
console.log('ambient_shell_quadratic_form_is_nondegenerate_with_distribution_0_10_1_6_2_6_3_10');
console.log('the_two_five_bit_groups_are_not_quadratically_isometric');
console.log('any_bridge_requires_an_additional_twist_puncture_or_orientation_line');
