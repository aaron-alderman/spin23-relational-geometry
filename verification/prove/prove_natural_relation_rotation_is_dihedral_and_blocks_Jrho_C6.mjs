import assert from "node:assert/strict";

const plus = ["PN", "NI", "IP"];
const minus = ["NP", "PI", "IN"];
const all = [...plus, ...minus];

const cycleMap = (cycle) => Object.fromEntries(cycle.map((x, i) => [x, cycle[(i + 1) % cycle.length]]));
const r = { ...cycleMap(plus), ...cycleMap(minus) };
const rInv = Object.fromEntries(Object.entries(r).map(([x, y]) => [y, x]));
const J = { PN: "NP", NP: "PN", NI: "IN", IN: "NI", IP: "PI", PI: "IP" };

const compose = (f, g) => Object.fromEntries(all.map((x) => [x, f[g[x]]])); // f after g
const identity = Object.fromEntries(all.map((x) => [x, x]));
const equalMap = (f, g) => all.every((x) => f[x] === g[x]);
const power = (f, n) => {
  let out = identity;
  for (let k = 0; k < n; k += 1) out = compose(f, out);
  return out;
};
const order = (f, max = 12) => {
  for (let n = 1; n <= max; n += 1) if (equalMap(power(f, n), identity)) return n;
  return null;
};

assert.ok(equalMap(compose(compose(J, r), J), rInv));
assert.equal(order(r), 3);
assert.equal(order(J), 2);

const reflections = [0, 1, 2].map((k) => {
  const T = compose(J, power(r, k));
  return { k, order: order(T), map: T };
});
assert.ok(reflections.every((x) => x.order === 2));

// The sheet-parallel rotation c is obtained by transporting the plus ordering
// through J, rather than using compositional order on the negative sheet.
const parallelMinus = ["NP", "IN", "PI"];
const c = { ...cycleMap(plus), ...cycleMap(parallelMinus) };
assert.ok(equalMap(compose(compose(J, c), J), c));
assert.equal(order(compose(J, c)), 6);

// But c traverses the negative sheet opposite to its natural compositional rotation.
assert.notEqual(c.NP, r.NP);
assert.equal(c.NP, rInv.NP);

const result = {
  protocol: "natural-relation-rotation-dihedral-no-Jrho-C6/1",
  orientedCompositionCycles: { plus, minus },
  exactRelation: "J r J = r^{-1}",
  generatedGroup: "D3 (dihedral group of the oriented triangle)",
  semilinearCandidates: reflections.map(({ k, order: ord }) => ({ candidate: "J r^" + k, order: ord })),
  noGo:
    "No transport J r^k built from KO reality and the natural oriented-composition rotation has order six; every such element is an order-two reflection.",
  abstractEscape: {
    transport: "J c",
    order: 6,
    cost: "c commutes with J only because it traverses the negative sheet opposite to its natural compositional direction",
  },
  theorem:
    "The abstract commuting-rotation C6 construction is incompatible with the natural relation-composition orientation. A physical Mobius lift requires a non-compositional parallel rotation or additional structure beyond the dihedral action generated by J and r.",
  passed: true,
};

