import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
const root=resolve(import.meta.dirname,"../..");
const result=JSON.parse(await readFile(resolve(root,"evidence/data/prophecy-chronology-combinatorics-v1.json"),"utf8"));
assert.equal(result.protocol,"prophetic-admissibility/chronology-combinatorics/1");
assert.equal(result.validationErrors.length,0);
assert.ok(result.coverage.catalogueElementCount>=180);
assert.ok(result.coverage.anchorCount>=20);
assert.ok(result.coverage.durationCount>=13);
assert.ok(result.enumeration.generatedCount>=100);
assert.ok(result.enumeration.retainedCount>10);
assert.ok(result.candidates.every((candidate)=>candidate.termCount<=3));
assert.ok(result.candidates.some((candidate)=>candidate.filterDisposition==="before-window"));
assert.ok(result.candidates.some((candidate)=>candidate.filterDisposition==="after-window"));
assert.ok(result.rankings.sourceExplicit.some((cluster)=>cluster.year===2060&&cluster.explicitNewton));
const cluster2046=result.rankings.independentTraditionConvergence.find((cluster)=>cluster.year===2046);
assert.equal(cluster2046.independentFamilyCount,2);
assert.equal(cluster2046.structuralDerivationCount,2);
const cluster2060=result.rankings.independentTraditionConvergence.find((cluster)=>cluster.year===2060);
assert.equal(cluster2060.independentFamilyCount,1);
assert.equal(cluster2060.structuralDerivationCount,1);
assert.ok(result.noDateLedger.some((entry)=>entry.id==="nh-apocadam-illuminator"));
console.log(JSON.stringify({result:"pass",protocol:result.protocol,generated:result.enumeration.generatedCount,retained:result.enumeration.retainedCount,clusters:result.enumeration.retainedClusterCount,rawTop:result.dominantSignals.raw[0],independentTop:result.dominantSignals.independent[0],sourceExplicitTop:result.dominantSignals.sourceExplicit[0]},null,2));
