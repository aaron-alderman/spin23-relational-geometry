import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
const ROOT = process.cwd();
const TARGET = "corpus/programmes/frontier-physics-targets/barrier_kinetic_propagation_audit_v1.json";
const read = p => fs.readFileSync(path.join(ROOT, p), "utf8");
const hash = text => crypto.createHash("sha256").update(text.replaceAll("\r\n", "\n")).digest("hex");
const audit = JSON.parse(read(TARGET));
const upstream = JSON.parse(read(audit.upstream.path));
const candidates = upstream.census.filter(record => record.route === audit.upstream.candidateRoute);
const failures = [];
if (audit.schema !== "frontier.barrier-kinetic-propagation-audit/1" || !audit.summary?.pass || audit.summary?.unreviewed !== 0) failures.push("audit open or schema mismatch");
if (hash(read(audit.reference.path)) !== audit.reference.sha256 || hash(read(audit.upstream.path)) !== audit.upstream.sha256) failures.push("stale source digest");
if (candidates.length !== audit.dispositions.length) failures.push("count mismatch");
const expected = new Set(candidates.map(record => record.path));
const observed = new Set(audit.dispositions.map(record => record.path));
if (observed.size !== audit.dispositions.length) failures.push("duplicate disposition");
for (const record of audit.dispositions) if (!expected.has(record.path) || !record.category || hash(read(record.path)) !== record.digest) failures.push(`invalid or stale ${record.path}`);
for (const record of candidates) if (!observed.has(record.path)) failures.push(`missing ${record.path}`);
console.log(JSON.stringify({ result: failures.length ? "fail" : "pass", target: TARGET, candidates: candidates.length, categories: audit.summary.byCategory, failures }, null, 2));
if (failures.length) process.exitCode = 1;
