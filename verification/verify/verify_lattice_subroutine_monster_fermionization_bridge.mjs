// Treat the ten even spin-sector amplitudes as independently graded variables.
// Every term in a bosonization sum has one unit vector as its multidegree;
// their product has all ten entries equal to one. Constant phases cannot make
// these two polynomial constructions proportional.
const sectorCount = 10;
const genus = 2;
const totalSpinStructures = 2 ** (2 * genus);
const evenSpinStructures = 2 ** (genus - 1) * (2 ** genus + 1);
const oddSpinStructures = 2 ** (genus - 1) * (2 ** genus - 1);
assert.deepEqual(
  { totalSpinStructures, evenSpinStructures, oddSpinStructures },
  { totalSpinStructures: 16, evenSpinStructures: 10, oddSpinStructures: 6 }
);
assert.equal(sectorCount, evenSpinStructures);
const additiveDegrees = Array.from({ length: sectorCount }, (_, i) =>
  Array.from({ length: sectorCount }, (__, j) => Number(i === j))
);
const chi5ProductDegree = Array(sectorCount).fill(1);
assert.equal(
  additiveDegrees.some((degree) =>
    degree.every((entry, i) => entry === chi5ProductDegree[i])
  ),
  false
);
const finiteSeamDeterminant = {
  positiveGroupElements: 360,
  negativeGroupElements: 360,
  character: "nontrivial sign character of Sp(4,F2)",
  analyticLift: "open"
};
assert.equal(finiteSeamDeterminant.positiveGroupElements + finiteSeamDeterminant.negativeGroupElements, 720);
assert.equal(finiteSeamDeterminant.positiveGroupElements, finiteSeamDeterminant.negativeGroupElements);

