const assert = (condition, message) => {
  if (!condition) throw new Error(message);
};

const matMul = (A, B) => A.map(row => B[0].map((_, j) => row.reduce((sum, x, k) => sum + x * B[k][j], 0)));
const matAdd = (...matrices) => matrices[0].map((row, i) => row.map((_, j) => matrices.reduce((sum, M) => sum + M[i][j], 0)));
const matScale = (a, A) => A.map(row => row.map(x => a * x));
const transpose = A => A[0].map((_, j) => A.map(row => row[j]));
const equal = (A, B, tolerance = 1e-12) => A.every((row, i) => row.every((x, j) => Math.abs(x - B[i][j]) <= tolerance));
const zero = n => Array.from({ length: n }, () => Array(n).fill(0));
const identity = n => Array.from({ length: n }, (_, i) => Array.from({ length: n }, (_, j) => Number(i === j)));
const unit = (n, i, j) => Array.from({ length: n }, (_, r) => Array.from({ length: n }, (_, c) => Number(r === i && c === j)));

const P = [
  [0, 1, 0],
  [0, 0, 1],
  [1, 0, 0]
];
const PT = transpose(P);
const P2 = matMul(P, P);
assert(equal(matMul(P2, P), identity(3)), 'cyclic permutation must have order three');

const vectorAverage = matScale(1 / 3, matAdd(identity(3), P, P2));
assert(equal(vectorAverage, [
  [1 / 3, 1 / 3, 1 / 3],
  [1 / 3, 1 / 3, 1 / 3],
  [1 / 3, 1 / 3, 1 / 3]
]), 'vector average must project onto the singlet line');

const conjugate = (X, power) => {
  if (power === 0) return X;
  if (power === 1) return matMul(matMul(P, X), PT);
  return matMul(matMul(P2, X), transpose(P2));
};
const expectation = X => matScale(1 / 3, matAdd(conjugate(X, 0), conjugate(X, 1), conjugate(X, 2)));

for (const basis of [identity(3), P, P2]) {
  assert(equal(expectation(basis), basis), 'circulant basis must be fixed under conjugation');
}

// Every expected matrix is circulant; the nine matrix units span only the
// three-dimensional space generated by I,P,P^2.
const flattenedImages = [];
for (let i = 0; i < 3; i += 1) {
  for (let j = 0; j < 3; j += 1) {
    flattenedImages.push(expectation(unit(3, i, j)).flat());
  }
}
const rank = rows => {
  const A = rows.map(row => [...row]);
  let r = 0;
  for (let c = 0; c < A[0].length && r < A.length; c += 1) {
    let pivot = r;
    while (pivot < A.length && Math.abs(A[pivot][c]) < 1e-10) pivot += 1;
    if (pivot === A.length) continue;
    [A[r], A[pivot]] = [A[pivot], A[r]];
    const value = A[r][c];
    A[r] = A[r].map(x => x / value);
    for (let i = 0; i < A.length; i += 1) {
      if (i === r) continue;
      const factor = A[i][c];
      A[i] = A[i].map((x, j) => x - factor * A[r][j]);
    }
    r += 1;
  }
  return r;
};
assert(rank(flattenedImages) === 3, 'fixed operator algebra must have dimension three');

// In the Fourier eigenbasis of P, the fixed circulant algebra is diagonal.
// For the diagonal expectation E_D on M3(C), the matrix units e_ij form a
// quasi-basis: X=sum_ij e_ij E_D(e_ji X), and the index is sum_ij e_ij e_ji=3I.
const diagonalExpectation = X => X.map((row, i) => row.map((x, j) => i === j ? x : 0));
const X = [
  [2, -1, 4],
  [3, 5, 7],
  [-2, 6, 1]
];
let reconstruction = zero(3);
let indexMatrix = zero(3);
for (let i = 0; i < 3; i += 1) {
  for (let j = 0; j < 3; j += 1) {
    const eij = unit(3, i, j);
    const eji = unit(3, j, i);
    reconstruction = matAdd(reconstruction, matMul(eij, diagonalExpectation(matMul(eji, X))));
    indexMatrix = matAdd(indexMatrix, matMul(eij, eji));
  }
}
assert(equal(reconstruction, X), 'matrix units must reconstruct every matrix through diagonal expectation');
assert(equal(indexMatrix, matScale(3, identity(3))), 'conditional-expectation index must be three');

