import assert from "node:assert/strict";

// Exact coefficient-vector check of local energy-momentum exchange in a
// two-field interaction V_int=(g/2) phi^2 chi^2.  We suppress the free
// Lorentz index nu and encode the two chain-rule monomials.
const divPhiStress = { phiChi2Dphi: -1, phi2ChiDchi: 0 };
const divChiStress = { phiChi2Dphi: 0, phi2ChiDchi: -1 };
const divInteractionStress = { phiChi2Dphi: 1, phi2ChiDchi: 1 };
const sumVectors = (...vectors) => Object.fromEntries(Object.keys(vectors[0]).map((key) =>
  [key, vectors.reduce((sum, vector) => sum + vector[key], 0)]));
assert.deepEqual(sumVectors(divPhiStress, divChiStress, divInteractionStress),
  { phiChi2Dphi: 0, phi2ChiDchi: 0 });
assert.notDeepEqual(divPhiStress, { phiChi2Dphi: 0, phi2ChiDchi: 0 });

const nodes = ["Q", "uc", "dc", "L", "ec", "H", "Gauge"];
const interactions = [
  { name: "upYukawa", nodes: ["Q", "uc", "H"] },
  { name: "downYukawa", nodes: ["Q", "dc", "H"] },
  { name: "chargedLeptonYukawa", nodes: ["L", "ec", "H"] },
  { name: "QGauge", nodes: ["Q", "Gauge"] },
  { name: "ucGauge", nodes: ["uc", "Gauge"] },
  { name: "dcGauge", nodes: ["dc", "Gauge"] },
  { name: "LGauge", nodes: ["L", "Gauge"] },
  { name: "ecGauge", nodes: ["ec", "Gauge"] },
  { name: "HGauge", nodes: ["H", "Gauge"] },
];

const closure = (seed) => {
  const selected = new Set(seed);
  const steps = [];
  let changed = true;
  while (changed) {
    changed = false;
    for (const interaction of interactions) {
      const touches = interaction.nodes.some((node) => selected.has(node));
      const crosses = interaction.nodes.some((node) => !selected.has(node));
      if (touches && crosses) {
        const added = interaction.nodes.filter((node) => !selected.has(node));
        for (const node of added) selected.add(node);
        steps.push({ interaction: interaction.name, added });
        changed = true;
      }
    }
  }
  return { selected: nodes.filter((node) => selected.has(node)), steps };
};

const leptonClosure = closure(["L"]);
assert.deepEqual(leptonClosure.selected, nodes);

const crossingInteractions = (subset) => {
  const selected = new Set(subset);
  return interactions.filter((interaction) =>
    interaction.nodes.some((node) => selected.has(node)) &&
    interaction.nodes.some((node) => !selected.has(node))).map((interaction) => interaction.name);
};
assert(crossingInteractions(["L"]).includes("chargedLeptonYukawa"));
assert(crossingInteractions(["L"]).includes("LGauge"));
assert.deepEqual(crossingInteractions(nodes), []);

