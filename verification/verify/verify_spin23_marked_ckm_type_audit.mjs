import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import path from "node:path";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const data=JSON.parse(readFileSync(path.join(root,"evidence/data/spin23-marked-ckm-type-audit.json"),"utf8"));
assert.equal(data.documentId,1488);
const P=[[1,0,0],[0,0,0],[0,0,0]],I=[[1,0,0],[0,1,0],[0,0,1]];
const X=I.map((r,i)=>r.map((x,j)=>x-3*P[i][j]));
assert.deepEqual(X,[[-2,0,0],[0,1,0],[0,0,1]]);
assert.equal(X[0][0]+X[1][1]+X[2][2],0);
assert.deepEqual(data.derivedGenerator.tracelessFamilyActionOnQuarks,[0,0,0]);
const rt=Math.sqrt(3)/2,G=[[-.5,-rt,0],[rt,-.5,0],[0,0,1]];
const Uu=[[1,0,0],[0,1,0],[0,0,1]],Ud=[[.8,-.6,0],[.6,.8,0],[0,0,1]];
const tr=A=>A[0].map((_,j)=>A.map(r=>r[j]));
const mul=(A,B)=>A.map(r=>B[0].map((_,j)=>r.reduce((s,x,k)=>s+x*B[k][j],0)));
const before=mul(tr(Uu),Ud),after=mul(tr(mul(G,Uu)),mul(G,Ud));
for(let i=0;i<3;i++)for(let j=0;j<3;j++)assert.ok(Math.abs(before[i][j]-after[i][j])<1e-14);
assert.equal(data.weakDoubletAudit.commonGaugeOrbitCreatesCkm,false);
assert.equal(data.weakDoubletAudit.relativeDownOnlyOrbitRequiresNewSectorSpurion,true);
assert.equal(data.claim1487Classification.algebraicWitnessValid,true);
assert.equal(data.claim1487Classification.derivedQuarkGaugeOrigin,false);
assert.equal(data.verdict.claim1487Retracted,false);
assert.equal(data.verdict.claim1487QualifiedAsCapacity,true);
assert.equal(data.verdict.physicalAdmissionChanged,false);
console.log("PASS 1488: the derived I-3P_alpha augmentation is lepton-family specific, and any common family gauge action on Q_L cancels from CKM; claim 1487 is capacity unless a new quark Yukawa spurion is derived.");
