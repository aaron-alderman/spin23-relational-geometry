import assert from "node:assert/strict";

const c = (re, im = 0) => ({ re, im });
const addc = (a, b) => c(a.re + b.re, a.im + b.im);
const mulc = (a, b) => c(a.re * b.re - a.im * b.im, a.re * b.im + a.im * b.re);
const conj = (a) => c(a.re, -a.im);
const scalec = (x, a) => c(x * a.re, x * a.im);
const mmul = (A, B) => A.map((row) => B[0].map((_, j) => row.reduce((s, x, k) => addc(s, mulc(x, B[k][j])), c(0))));
const dagger = (A) => A[0].map((_, j) => A.map((row) => conj(row[j])));
const madd = (A, B) => A.map((row, i) => row.map((z, j) => addc(z, B[i][j])));
const mscale = (x, A) => A.map((row) => row.map((z) => scalec(x, z)));
const msub = (A, B) => madd(A, mscale(-1, B));
const commutator = (A, B) => msub(mmul(A, B), mmul(B, A));
const diagonal = (xs) => xs.map((x, i) => xs.map((_, j) => c(i === j ? x : 0)));
const det3 = (A) => {
  const term = (i, j, k) => mulc(A[0][i], mulc(A[1][j], A[2][k]));
  return addc(addc(term(0, 1, 2), term(1, 2, 0)), addc(term(2, 0, 1), scalec(-1, addc(addc(term(2, 1, 0), term(1, 0, 2)), term(0, 2, 1)))));
};
const trace = (A) => A.reduce((s, row, i) => addc(s, row[i]), c(0));
const maxAbs = (A) => Math.max(...A.flat().map((z) => Math.hypot(z.re, z.im)));

const mixing = (delta) => {
  const c12 = 0.974, s12 = Math.sqrt(1 - c12 * c12);
  const c23 = 0.999, s23 = Math.sqrt(1 - c23 * c23);
  const s13 = 0.0037, c13 = Math.sqrt(1 - s13 * s13);
  const em = c(Math.cos(delta), -Math.sin(delta)), ep = conj(em);
  return [
    [c(c12 * c13), c(s12 * c13), scalec(s13, em)],
    [addc(c(-s12 * c23), scalec(-c12 * s23 * s13, ep)), addc(c(c12 * c23), scalec(-s12 * s23 * s13, ep)), c(s23 * c13)],
    [addc(c(s12 * s23), scalec(-c12 * c23 * s13, ep)), addc(c(-c12 * s23), scalec(-s12 * c23 * s13, ep)), c(c23 * c13)],
  ];
};

const Hu = diagonal([1, 4, 11]);
const Dd = diagonal([2, 7, 19]);
const V = mixing(1.2);
const Hd = mmul(V, mmul(Dd, dagger(V)));
const massCommutator = commutator(Hu, Hd);

// For graph family V_graph(x,y)=exp(i x Hu)exp(i y Hd):
// theta_x=-iHu, theta_y=-iHd, and F_xy=-1/4[theta_x,theta_y]=1/4[Hu,Hd].
const curvature = mscale(0.25, massCommutator);
const curvatureDet = det3(curvature);
const commutatorDet = det3(massCommutator);
assert(Math.abs(curvatureDet.re) < 1e-10);
assert(Math.abs(curvatureDet.im) > 1e-6);
assert(Math.abs(curvatureDet.im - commutatorDet.im / 64) < 1e-10);
assert(maxAbs(msub(madd(curvature, dagger(curvature)), diagonal([0, 0, 0]))) < 1e-12);

const traceCube = trace(mmul(curvature, mmul(curvature, curvature)));
assert(Math.abs(traceCube.im - 3 * curvatureDet.im) < 1e-10);
assert(Math.abs(traceCube.re) < 1e-10);

// CP conjugation complex-conjugates the mass data and reverses the CP-odd sign.
const Vcp = V.map((row) => row.map(conj));
const Hdcp = mmul(Vcp, mmul(Dd, dagger(Vcp)));
const curvatureCpDet = det3(mscale(0.25, commutator(Hu, Hdcp)));
assert(Math.abs(curvatureCpDet.im + curvatureDet.im) < 1e-10);

// Remove the CKM phase: the CP-odd determinant vanishes.
const Vreal = mixing(0);
const Hdreal = mmul(Vreal, mmul(Dd, dagger(Vreal)));
const realPhaseCurvatureDet = det3(mscale(0.25, commutator(Hu, Hdreal)));
assert(Math.abs(realPhaseCurvatureDet.im) < 1e-10);

// A degenerate up spectrum also kills the invariant.
const HuDegenerate = diagonal([1, 1, 11]);
const degenerateCurvatureDet = det3(mscale(0.25, commutator(HuDegenerate, Hd)));
assert(Math.hypot(degenerateCurvatureDet.re, degenerateCurvatureDet.im) < 1e-10);

