#!/usr/bin/env node

const cross=(a,b)=>[
  a[1]*b[2]-a[2]*b[1],
  a[2]*b[0]-a[0]*b[2],
  a[0]*b[1]-a[1]*b[0]
];
const ex=[1,0,0],ey=[0,1,0],ez=[0,0,1];
const generators={Tx:ex,Ty:ey,Tz:ez};
const preservesRealPlane=omega=>{
  const dx=cross(omega,ex),dz=cross(omega,ez);
  return dx[1]===0&&dz[1]===0;
};
const preservesDiagonalLine=omega=>{
  const dz=cross(omega,ez);
  return dz[0]===0&&dz[1]===0;
};
const table=Object.fromEntries(Object.entries(generators).map(([name,omega])=>[
  name,{preservesH2R:preservesRealPlane(omega),preservesDiagonal:preservesDiagonalLine(omega)}
]));
const h2rGenerators=Object.entries(table).filter(([,v])=>v.preservesH2R).map(([k])=>k);
const diagonalGenerators=Object.entries(table).filter(([,v])=>v.preservesDiagonal).map(([k])=>k);
const commonGenerators=Object.entries(table).filter(([,v])=>v.preservesH2R&&v.preservesDiagonal).map(([k])=>k);
const report={
  protocol:"weak-real-form-stabilizers/1",
  pauliCoordinates:{
    H2C:"span_R{I,sigma1,sigma2,sigma3}",
    H2R:"span_R{I,sigma1,sigma3}",
    diagonal:"span_R{I,sigma3}"
  },
  infinitesimalGeneratorTable:table,
  connectedStabilizerLieAlgebras:{
    H2R:h2rGenerators,
    diagonal:diagonalGenerators,
    common:commonGenerators
  },
  centralHyperchargeConjugation:"trivial on H2(C)",
  conclusion:[
    "The connected SU(2) stabilizer of H2(R) is generated by Ty.",
    "The connected SU(2) stabilizer of the chosen diagonal algebra is generated by Tz.",
    "No nonzero continuous SU(2) generator preserves both nested subalgebras in this basis.",
    "Therefore the Jordan inclusions do not by themselves define one nested electroweak breaking chain."
  ]
};
report.passed=h2rGenerators.length===1&&h2rGenerators[0]==="Ty"&&
  diagonalGenerators.length===1&&diagonalGenerators[0]==="Tz"&&commonGenerators.length===0;
console.log(JSON.stringify(report,null,2));
if(!report.passed)process.exitCode=1;
