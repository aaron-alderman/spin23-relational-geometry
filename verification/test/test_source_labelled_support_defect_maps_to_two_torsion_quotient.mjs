const det = (A) => A.length===0?1:A.length===1?A[0][0]:A[0].reduce(
  (s,x,j)=>s+(j%2?-1:1)*x*det(A.slice(1).map((r)=>r.filter((_,k)=>k!==j))),0
);
const transpose = (A) => A[0].map((_,j)=>A.map((r)=>r[j]));
const mv = (A,v) => A.map((r)=>r.reduce((s,x,i)=>s+x*v[i],0));
const add = (a,b) => a.map((x,i)=>x+b[i]);
const scale = (n,a) => a.map((x)=>n*x);
const xor = (a,b) => a.map((x,i)=>x^b[i]);
const mod = (x,n) => ((x%n)+n)%n;
const key = (v) => v.join(",");
const bits = (n,width) => Array.from({length:width},(_,i)=>(n>>i)&1);
const rank2 = (rows) => {
  const A=rows.map((r)=>r.slice());
  let rank=0;
  for(let col=0;col<A[0].length&&rank<A.length;col++){
    let p=rank;
    while(p<A.length&&!A[p][col])p++;
    if(p===A.length)continue;
    [A[rank],A[p]]=[A[p],A[rank]];
    for(let i=0;i<A.length;i++)if(i!==rank&&A[i][col])A[i]=xor(A[i],A[rank]);
    rank++;
  }
  return rank;
};
const adjugate = (A) => transpose(A.map((_,i)=>A.map((__,j)=>{
  const minor=A.filter((_,r)=>r!==i).map((row)=>row.filter((_,c)=>c!==j));
  return ((i+j)%2?-1:1)*det(minor);
})));

// Actual common-intersection quotient G=M/I in M-basis order (v,w,r,s,t).
