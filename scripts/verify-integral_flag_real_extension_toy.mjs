#!/usr/bin/env node

const mul=(A,B)=>A.map(r=>B[0].map((_,j)=>r.reduce((s,x,k)=>s+x*B[k][j],0)));
const tr=A=>A[0].map((_,j)=>A.map(r=>r[j]));
const det2=A=>A[0][0]*A[1][1]-A[0][1]*A[1][0];
const maxerr=(A,B)=>Math.max(...A.flatMap((r,i)=>r.map((x,j)=>Math.abs(x-B[i][j]))));
const act=(g,X)=>mul(mul(g,X),tr(g));
const E11=[[1,0],[0,0]];
const X=[[2,3],[3,5]];
const gb=b=>[[1,b],[0,1]];
const samples=[-2,-1,0,0.5,Math.sqrt(2),3].map(b=>{
  const g=gb(b),Y=act(g,X);
  return {
    b,g,
    determinantOne:Math.abs(det2(g)-1)<1e-12,
    fixesFlagGenerator:maxerr(act(g,E11),E11)<1e-12,
    transformed:Y,
    preservesSym2Z:Number.isInteger(b)&&Y.flat().every(Number.isInteger)
  };
});
const report={
  protocol:"integral-flag-real-extension-toy/1",
  order:"J_Z=Sym_2(Z) with determinant norm",
  scalarExtension:"J_R=J_Z tensor R=Sym_2(R)",
  selectedFlag:"primitive rank-one ray generated by E_11",
  realStabilizer:{
    subgroup:"g_b=[[1,b],[0,1]], b in R, inside SL(2,R)",
    connected:true,
    dimension:1,
    actionFormula:"(a,c,d) -> (a+2bc+b^2 d, c+bd, d)"
  },
  integralStabilizer:{
    subgroup:"g_b with b in Z",
    discrete:true,
    arithmeticInsideRealStabilizer:true
  },
  samples,
  checks:{
    everySampleFixesRealFlag:samples.every(s=>s.determinantOne&&s.fixesFlagGenerator),
    integerSamplesPreserveOrder:samples.filter(s=>Number.isInteger(s.b)).every(s=>s.preservesSym2Z),
    nonintegerSamplesFailOrder:samples.filter(s=>!Number.isInteger(s.b)).every(s=>!s.preservesSym2Z)
  },
  exceptionalTemplate:[
    "Choose an integral exceptional-Jordan order J_Z.",
    "Define primitive integral suborders realizing the nested flag.",
    "Compute the stabilizer group scheme over Z and its integral points.",
    "Base-change the same flag to R or C and compute the identity component.",
    "Only then compare the real stabilizer with the Standard-Model group and the integral stabilizer with Leech/charge data."
  ],
  conclusion:"Arithmetic flag selection and continuous stabilizer symmetry can coexist at different scalar levels; the toy proves the architecture, not the exceptional-Jordan instance."
};
report.passed=report.checks.everySampleFixesRealFlag&&
  report.checks.integerSamplesPreserveOrder&&report.checks.nonintegerSamplesFailOrder;
console.log(JSON.stringify(report,null,2));
if(!report.passed)process.exitCode=1;
