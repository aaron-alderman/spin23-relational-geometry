import assert from 'node:assert/strict';

const blocks = { O1: [0], O2: [1, 2, 3], H: [4, 5], C: [6], R: [7] };
const n = 8;
const unit = (row, col) => {
  const v = Array(n * n).fill(0);
  v[row * n + col] = 1;
  return v;
};
const block = (target, source) => {
  const out = [];
  for (const r of blocks[target]) for (const c of blocks[source]) out.push(unit(r, c));
  return out;
};
const transpose = a => Array.from({ length: n * n }, (_, q) => a[(q % n) * n + Math.floor(q / n)]);
const matMul = (a, b) => {
  const c = Array(n * n).fill(0);
  for (let i = 0; i < n; i++) for (let k = 0; k < n; k++) {
    const x = a[i * n + k];
    if (!x) continue;
    for (let j = 0; j < n; j++) c[i * n + j] += x * b[k * n + j];
  }
  return c;
};
const add = (a, b) => a.map((x, i) => x + b[i]);
const triple = (x, y, z) => matMul(matMul(x, transpose(y)), z);
const maxAbs = a => Math.max(...a.map(Math.abs));

class Span {
  constructor(vectors = []) { this.rows = []; this.pivots = []; for (const v of vectors) this.add(v); }
  add(input) {
    const v = input.slice();
    for (let k = 0; k < this.rows.length; k++) {
      const p = this.pivots[k];
      if (!v[p]) continue;
      const q = v[p] / this.rows[k][p];
      for (let j = p; j < v.length; j++) v[j] -= q * this.rows[k][j];
    }
    const p = v.findIndex(x => Math.abs(x) > 1e-10);
    if (p < 0) return false;
    const q = v[p];
    for (let j = p; j < v.length; j++) v[j] /= q;
    let pos = this.pivots.findIndex(x => x > p);
    if (pos < 0) pos = this.pivots.length;
    this.pivots.splice(pos, 0, p);
    this.rows.splice(pos, 0, v);
    for (let k = 0; k < this.rows.length; k++) if (k !== pos && Math.abs(this.rows[k][p]) > 1e-10) {
      const f = this.rows[k][p];
      for (let j = p; j < v.length; j++) this.rows[k][j] -= f * v[j];
    }
    return true;
  }
  contains(v) { const before = this.rows.length; const added = this.add(v); if (added) throw new Error('destructive contains call on vector outside span'); return this.rows.length === before; }
}

const closureSpan = seed => {
  const span = new Span(seed);
  let changed = true;
  while (changed) {
    changed = false;
    const basis = span.rows.map(v => v.slice());
    outer: for (const x of basis) for (const y of basis) for (const z of basis) {
      if (span.add(triple(x, y, z))) { changed = true; break outer; }
    }
  }
  return span;
};

const matterA = [
  ...block('O2', 'H'), ...block('C', 'O2'), ...block('O1', 'O2'),
  ...block('H', 'R'), ...block('R', 'C'),
];
const a = unit(blocks.R[0], blocks.O1[0]);
const adag = transpose(a);

// Exact one-mode CAR on span{O1,R}.
assert(maxAbs(matMul(a, a)) === 0);
assert(maxAbs(matMul(adag, adag)) === 0);
const anticommutator = add(matMul(a, adag), matMul(adag, a));
const neutralIdentity = add(unit(blocks.O1[0], blocks.O1[0]), unit(blocks.R[0], blocks.R[0]));
assert(maxAbs(anticommutator.map((x, i) => x - neutralIdentity[i])) === 0);

// The four neutral matrix units are generated by a, a† and their products.
const neutralAlgebra = new Span([a, adag, matMul(a, adag), matMul(adag, a)]);
assert.equal(neutralAlgebra.rows.length, 4);

const forward = closureSpan([...matterA, a]);
assert.equal(forward.rows.length, 16);

const reverseAsIndependent = closureSpan([...matterA, adag]);
assert.equal(reverseAsIndependent.rows.length, 23);

const bothAsMatter = closureSpan([...matterA, a, adag]);
assert.equal(bothAsMatter.rows.length, 24);

console.log('Local CAR and matter-TRO enlargement certificate: PASS');
console.log(`CAR=M2(C); forward_matter_dim=16; reverse_independent_dim=${reverseAsIndependent.rows.length}; both_independent_dim=${bothAsMatter.rows.length}`);
