import assert from "node:assert/strict";

const bits=(n,k)=>Array.from({length:k},(_,i)=>(n>>i)&1);
const xor=(a,b)=>a.map((x,i)=>x^b[i]);
const key=v=>v.join("");
const rank2=rows=>{
  const A=rows.map(r=>r.slice());let rank=0;
  for(let c=0;c<3&&rank<A.length;c++){
    let p=rank;while(p<A.length&&!A[p][c])p++;
    if(p===A.length)continue;[A[rank],A[p]]=[A[p],A[rank]];
    for(let i=0;i<A.length;i++)if(i!==rank&&A[i][c])A[i]=xor(A[i],A[rank]);
    rank++;
  }return rank;
};
const tails=Array.from({length:8},(_,n)=>bits(n,3)); // coordinates (w,s,t)
const GL3=[];
for(let n=0;n<512;n++){
  const z=bits(n,9),A=Array.from({length:3},(_,i)=>z.slice(3*i,3*i+3));
  if(rank2(A)===3)GL3.push(A);
}
assert.equal(GL3.length,168);
const mv=(A,v)=>A.map(r=>r.reduce((s,x,i)=>s^(x&v[i]),0));

// A phase-compatible labelled section is determined by two lifts
// g1=(-r+u1), g2=(-r+u2), with distinct binary tails.
const sections=[];
for(const u1 of tails)for(const u2 of tails)if(key(u1)!==key(u2))sections.push([u1,u2]);
assert.equal(sections.length,56);

// Aut(G,chi) is AGL(3,2): r -> r+u0 and u -> A u.
// On -r+ui this sends the tail to A ui + u0.
const automorphisms=[];
for(const u0 of tails)for(const A of GL3)automorphisms.push({u0,A});
assert.equal(automorphisms.length,1344);
const act=({u0,A},[u1,u2])=>[xor(mv(A,u1),u0),xor(mv(A,u2),u0)];
const chosen=[[0,1,0],[0,0,1]]; // tails s,t
const orbit=new Set(automorphisms.map(g=>act(g,chosen).map(key).join("|")));
assert.equal(orbit.size,56);
const stabilizer=automorphisms.filter(g=>act(g,chosen).map(key).join("|")===chosen.map(key).join("|"));
assert.equal(stabilizer.length,24);
const unorderedStabilizer=automorphisms.filter(g=>{
  const image=act(g,chosen).map(key).sort().join("|");
  return image===chosen.map(key).sort().join("|");
});
assert.equal(unorderedStabilizer.length,48);

// Once the quotient tails are field-labelled as s and t, odd chi fixes the
// r coefficient to -1, so the section is unique.
const labelledSections=sections.filter(([u1,u2])=>key(u1)==="010"&&key(u2)==="001");
assert.equal(labelledSections.length,1);

// The subgroup generated by the two lifts has relations
// g1^2=g2^2=z, z^2=1, [g1,g2]=1, hence Z4 x Z2, not D8/Q8.
// Enumerate abstractly as (n,m) -> n g1 + m g2 with n,m mod4 and identify
// the common square relation 2g1=2g2.
const subgroup=new Set();
for(let n=0;n<4;n++)for(let m=0;m<4;m++){
  const rCoeff=((3*n+3*m)%4+4)%4;
  const tail=xor((n%2)?chosen[0]:[0,0,0],(m%2)?chosen[1]:[0,0,0]);
  subgroup.add(rCoeff+"|"+key(tail));
}
assert.equal(subgroup.size,8);

