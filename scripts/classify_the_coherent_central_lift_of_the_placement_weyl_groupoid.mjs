import assert from 'node:assert/strict';

const c = (re, im = 0) => [re, im];
const add = ([a, b], [d, e]) => [a + d, b + e];
const mul = ([a, b], [d, e]) => [a * d - b * e, a * e + b * d];
const mm = (A, B) => A.map((r) => B[0].map((_, j) => r.reduce((s, x, k) => add(s, mul(x, B[k][j])), c(0))));
const scale = (z, A) => A.map((r) => r.map((x) => mul(z, x)));
const eq = (A, B) => A.every((r, i) => r.every((x, j) => Math.hypot(x[0] - B[i][j][0], x[1] - B[i][j][1]) < 1e-12));
const key = (A) => A.flat().map(([a, b]) => `${Math.round(a)},${Math.round(b)}`).join(';');
const real = (A) => A.map((r) => r.map((x) => c(x)));
const I = real([[1, 0], [0, 1]]), Z = scale(c(-1), I);
const A = real([[0, -1], [1, -1]]);
const F = real([[1, 0], [1, -1]]);
const FA = mm(F, A);
const X = scale(c(0, 1), F); // sideband-reversed coherent handle face
const Y = scale(c(0, -1), FA); // positive-sideband adjacent face

assert.ok(eq(mm(mm(A, A), A), I));
assert.ok(eq(mm(X, X), Z));
assert.ok(eq(mm(Y, Y), Z));
assert.ok(eq(mm(X, Y), A));
const sameSidebandX = scale(c(-1), X);
assert.ok(eq(mm(sameSidebandX, Y), mm(Z, A)));
assert.ok(eq(mm(mm(mm(Z, A), mm(Z, A)), mm(Z, A)), Z));

// Enumerate the coherent lift generated by A and X.
const group = new Map([[key(I), I]]);
let changed = true;
while (changed) {
  changed = false;
  for (const G of [...group.values()]) for (const H of [A, X]) {
    for (const K of [mm(G, H), mm(H, G)]) if (!group.has(key(K))) { group.set(key(K), K); changed = true; }
  }
}
assert.equal(group.size, 12);
const order = (M) => { let P = I; for (let n = 1; n <= 24; n++) { P = mm(P, M); if (eq(P, I)) return n; } throw new Error('order too large'); };
const histogram = {};
for (const G of group.values()) histogram[order(G)] = (histogram[order(G)] ?? 0) + 1;
assert.deepEqual(histogram, { 1: 1, 2: 1, 3: 2, 4: 6, 6: 2 });

// The real normalizer has the same cardinality but a different extension class.
const realWeyl = new Map([[key(I), I]]);
changed = true;
while (changed) {
  changed = false;
  for (const G of [...realWeyl.values()]) for (const H of [A, F]) {
    for (const K of [mm(G, H), mm(H, G)]) if (!realWeyl.has(key(K))) { realWeyl.set(key(K), K); changed = true; }
  }
}
const realNormalizer = new Map();
for (const G of realWeyl.values()) { realNormalizer.set(key(G), G); realNormalizer.set(key(scale(c(-1), G)), scale(c(-1), G)); }
const realHistogram = {};
for (const G of realNormalizer.values()) realHistogram[order(G)] = (realHistogram[order(G)] ?? 0) + 1;
assert.deepEqual(realHistogram, { 1: 1, 2: 7, 3: 2, 6: 2 });

