import assert from 'node:assert/strict';

const rt3 = Math.sqrt(3);
const addV = (u, v) => u.map((x, i) => x + v[i]);
const add = (A, B) => A.map((row, i) => row.map((x, j) => x + B[i][j]));
const sub = (A, B) => A.map((row, i) => row.map((x, j) => x - B[i][j]));
const scale = (a, A) => A.map(row => row.map(x => a * x));
const outer2 = (u, v) => u.map(x => v.map(y => x * y));
const sigma = v => outer2(v, v);
const eq = (A, B, eps = 1e-11) => A.every((row, i) => row.every((x, j) => Math.abs(x - B[i][j]) < eps));
const eqV = (u, v, eps = 1e-11) => u.every((x, i) => Math.abs(x - v[i]) < eps);
const gp = [1, rt3], gm = [1, -rt3], g0 = [-2, 0];
const sum = addV(gp, gm);
assert.ok(eqV(sum, g0.map(x => -x)));

const Sp = sigma(gp), Sm = sigma(gm), S0 = sigma(g0), Ssum = sigma(sum);
assert.ok(eq(Ssum, S0));

const polarizedCross = scale(1 / 2, sub(sub(Ssum, Sp), Sm));
const directCross = scale(1 / 2, add(outer2(gp, gm), outer2(gm, gp)));
assert.ok(eq(polarizedCross, directCross));
assert.ok(eq(polarizedCross, [[1, 0], [0, -3]]));

const completed = add(add(Sp, Sm), Ssum);
assert.ok(eq(completed, [[6, 0], [0, 6]]));

// Phase/coherence audit. For a relative real sign s, sigma(gp+s gm)
// equals the third root projector only at s=+1; incoherent averaging omits
// the cross term and remains anisotropic.
const coherentMinus = sigma(addV(gp, gm.map(x => -x)));
assert.ok(eq(coherentMinus, [[0, 0], [0, 12]]));
const incoherent = add(Sp, Sm);
assert.ok(eq(incoherent, [[2, 0], [0, 6]]));

console.log(JSON.stringify({
  protocol: 'third-a2-root-from-feshbach-polarization/1',
  faceCouplings: { gPlus: gp, gMinus: gm, coherentSum: sum, thirdRoot: g0 },
  quadraticMap: 'Sigma(g) = g g^T',
  identities: {
    thirdProjector: 'Sigma(gPlus + gMinus) = Sigma(-gZero) = gZero gZero^T',
    jordanPolarization: '1/2[ Sigma(gPlus+gMinus)-Sigma(gPlus)-Sigma(gMinus) ] = 1/2(gPlus gMinus^T + gMinus gPlus^T)',
    polarizedCross,
    completedOrbitSum: completed,
  },
  coherenceAudit: {
    relativePlus: 'produces the missing horizontal root projector',
    relativeMinus: coherentMinus,
    incoherentMixture: incoherent,
    verdict: 'the third equal-weight relationship requires coherent in-phase superposition under one common quadratic propagator',
  },
  consequence: 'The third A2 projector is generated by the same quadratic Feshbach map whose polarization is the Jordan triple; it need not be a new mediator channel.',
  passed: true,
}, null, 2));
