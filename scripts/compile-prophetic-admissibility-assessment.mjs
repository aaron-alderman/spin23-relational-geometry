import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const read = async (path) => JSON.parse(await readFile(resolve(root, path), "utf8"));
const [admission, sensitivity, controls, tournament, transforms, majors, sourceAudit] = await Promise.all([
  read("evidence/data/prophetic-admissibility-pilot-v0-result.json"),
  read("evidence/data/prophetic-historical-sensitivity-v0-result.json"),
  read("evidence/data/prophetic-interpreter-forecasts-v0-result.json"),
  read("evidence/data/prophetic-operator-tournament-v0.json"),
  read("evidence/data/biblical-time-transform-ranking-v0.json"),
  read("evidence/data/prophetic-major-candidates-v0-result.json"),
  read("evidence/data/prophetic-source-audit-v0.json")
]);

const majorCandidates = majors.compiledFamilies.flatMap((family) => family.candidates.map((candidate) => ({
  familyId: family.id,
  id: candidate.id,
  operator: candidate.operator,
  temporalClaim: candidate.temporalClaim,
  temporalStatus: candidate.temporalAudit.status,
  predictiveWeight: candidate.predictiveWeight,
  disposition: candidate.id === "newton-day-year-2060"
    ? "retained as an unweighted lower-bound candidate; no positive evidential lift"
    : candidate.temporalAudit.status === "window-elapsed-outcome-uncoded"
      ? "historically elapsed; cannot be scored until the broad target predicate is independently coded"
      : "generated but unweighted"
})));

const result = {
  protocol: "prophetic-admissibility/programme-assessment/0",
  generatedAt: "2026-10-28",
  programmeOperational: true,
  evidenceState: {
    sourceAdmissionCases: admission.caseCount,
    primaryPredictiveCases: admission.predictiveCalibrationAdmittedCount,
    historicalSensitivityCases: sensitivity.sensitivityEligibleCount,
    modernClosedControls: controls.closedRecordCount,
    exactTerminalFailuresInSelectedControl: controls.exactTerminalControl.missCount,
    externalLocatorsAudited: sourceAudit.sourceCount,
    locatorCoverageComplete: sourceAudit.locatorCoverageComplete,
    bibliographicMetadataComplete: sourceAudit.bibliographicMetadataComplete
  },
  rankings: {
    textualTransformRanking: {
      identified: true,
      kind: "ordinal source-scope ranking, not predictive probability",
      orderedTransformIds: transforms.ranking.map((entry) => entry.id)
    },
    retrospectiveControlRanking: {
      identified: true,
      winner: tournament.winner,
      heldOutIds: tournament.heldOutIds,
      limitation: tournament.design.limitation
    },
    positivePredictiveHermeneuticRanking: {
      identified: tournament.positiveHermeneuticRankingIdentified && admission.predictiveRankingIdentified,
      reason: "No ancient case passes the strict primary admission gates, and the selected modern held-out control validates only an adverse ranking against exact terminal arithmetic."
    }
  },
  frozenRankingApplication: {
    status: "partial-adverse-only",
    appliedRule: "Do not award predictive weight merely because a terminal date is generated by exact arithmetic; retain source-scope ranking separately from historical prediction ranking.",
    majorCandidates
  },
  answer: {
    strongestSupportedConclusion: "The current evidence ranks exact terminal arithmetic below the skeptical null in the selected held-out control and supplies no validated positive operator for an open major prophecy.",
    newton2060: "AD 2060 survives only as Newton's unweighted [2060, infinity) lower-bound candidate. It is neither an exact end-date prediction nor validated by the minor-prophecy calibration.",
    theologicalBoundary: "Failure to identify a predictive operator is evidence about this method and corpus, not a proof against God, inspiration, providence or non-predictive functions of prophecy. Conversely, textual resonance and mathematical elegance are not evidence of divine agency without an independently validated predictive residue."
  },
  completionState: {
    schemaAndExecutionComplete: true,
    positiveValidationComplete: false,
    blockers: [
      "zero primary-admitted ancient predictive cases",
      "no independently encoded representative calibration population",
      "no prospective held-out replication",
      "secondary-source bibliography and content hashes not fully frozen"
    ],
    nextFalsifiableMilestone: "Freeze and independently encode a predeclared population containing enough D0/D1 closed cases for lineage-separated training and held-out evaluation; rerun without changing gates, predicates or operators."
  }
};

if (process.argv.includes("--write")) {
  await writeFile(resolve(root, "evidence/data/prophetic-admissibility-assessment-v0.json"), `${JSON.stringify(result, null, 2)}\n`, "utf8");
}

