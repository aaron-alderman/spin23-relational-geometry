import assert from 'node:assert/strict';

const mm = (A, B) => A.map(row => B[0].map((_, j) => row.reduce((s, x, k) => s + x * B[k][j], 0)));
const tr = A => A[0].map((_, j) => A.map(row => row[j]));
const add = (A, B) => A.map((row, i) => row.map((x, j) => x + B[i][j]));
const neg = A => A.map(row => row.map(x => -x));
const eq = (A, B, eps = 1e-12) => A.every((row, i) => row.every((x, j) => Math.abs(x - B[i][j]) < eps));
const block = (A, B, C, D) => A.map((row, i) => [...row, ...B[i]]).concat(C.map((row, i) => [...row, ...D[i]]));
const zero = (m, n) => Array.from({ length: m }, () => Array(n).fill(0));
const I = n => Array.from({ length: n }, (_, i) => Array.from({ length: n }, (_, j) => Number(i === j)));
const key = A => A.flat().join(',');
const eps = [[0, 1], [-1, 0]];
const J = block(eps, zero(2, 2), zero(2, 2), neg(eps));
const A = [[1, 3], [-1, -2]];
const X = [[1, 1], [0, -1]];
const R = block(I(2), zero(2, 2), zero(2, 2), A);
const H = block(zero(2, 2), X, X, zero(2, 2));
const I4 = I(4);

assert.ok(eq(mm(mm(tr(R), J), R), J));
assert.ok(eq(mm(mm(tr(H), J), H), J));
assert.ok(eq(mm(mm(R, R), R), I4));
assert.ok(eq(mm(H, H), I4));

// Graph(H) inside V^- direct-sum V is Lagrangian exactly because H is
// symplectic. Columns of graphBasis are (v,Hv).
const doubledJ = block(neg(J), zero(4, 4), zero(4, 4), J);
const graphBasis = I4.map((row, i) => [...row]).concat(H.map(row => [...row]));
assert.ok(eq(mm(mm(tr(graphBasis), doubledJ), graphBasis), zero(4, 4)));
// The top 4x4 minor is the identity, so the integral graph is primitive.
const primitiveGraph = true;

// Enumerate the finite selector group generated by R and H.
const generators = [R, H];
const group = [I4];
const seen = new Set([key(I4)]);
for (let cursor = 0; cursor < group.length; cursor++) {
  for (const g of generators) {
    const next = mm(group[cursor], g);
    if (!seen.has(key(next))) {
      seen.add(key(next));
      group.push(next);
    }
  }
}
assert.equal(group.length, 18);

// Finite-group averaging produces a positive invariant energy metric.
let G = zero(4, 4);
for (const g of group) G = add(G, mm(tr(g), g));
assert.ok(eq(mm(mm(tr(R), G), R), G));
assert.ok(eq(mm(mm(tr(H), G), H), G));

// Sylvester criterion for the explicit symmetric matrix.
const det = M => {
  if (M.length === 1) return M[0][0];
  return M[0].reduce((sum, x, j) => {
    const minor = M.slice(1).map(row => row.filter((_, k) => k !== j));
    return sum + (j % 2 ? -1 : 1) * x * det(minor);
  }, 0);
};
const leadingMinors = [1, 2, 3, 4].map(n => det(G.slice(0, n).map(row => row.slice(0, n))));
assert.ok(leadingMinors.every(x => x > 0));

