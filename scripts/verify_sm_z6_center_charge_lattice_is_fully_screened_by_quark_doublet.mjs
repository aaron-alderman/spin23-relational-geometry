import assert from "node:assert/strict";

const mod = (x, n) => ((x % n) + n) % n;
const key = ([t, s, y]) => `${mod(t,3)},${mod(s,2)},${mod(y,6)}`;
const add = (a, b) => [mod(a[0]+b[0],3), mod(a[1]+b[1],2), mod(a[2]+b[2],6)];

// Representations of (SU3 x SU2 x U1)/Z6 obey 2t+3s+y=0 mod 6.
const allowed = [];
for (let t=0;t<3;t++) for (let s=0;s<2;s++) for (let y=0;y<6;y++) if (mod(2*t+3*s+y,6)===0) allowed.push([t,s,y]);
assert.equal(allowed.length,6);

const Q=[1,1,1];
const cyclic=[];
let x=[0,0,0];
for(let n=0;n<6;n++){cyclic.push(x);x=add(x,Q);}
assert.equal(new Set(cyclic.map(key)).size,6);
assert.deepEqual(new Set(cyclic.map(key)),new Set(allowed.map(key)));

// Other matter center charges are powers of Q in this finite quotient.
const matter={Q:[1,1,1],uc:[2,0,2],dc:[2,0,2],L:[0,1,3],ec:[0,0,0],nuc:[0,0,0],H:[0,1,3]};
for(const charge of Object.values(matter)) assert(cyclic.some((v)=>key(v)===key(charge)));

// The fundamental group kernel of determinant winding (m,n)->m+n is Z,
// generated by (1,-1), and has no torsion element.
for(let m=-20;m<=20;m++) for(let n=-20;n<=20;n++) if(m+n===0) assert(n===-m);

