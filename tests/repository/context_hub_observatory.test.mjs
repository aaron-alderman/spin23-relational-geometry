function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "spin23-observatory-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = join(root, "corpus", "programmes");
  mkdirSync(directory, { recursive: true });
  const content = "# Boundary response candidate\n\nA boundary response candidate for controlled context selection.\n";
  for (const name of ["alpha.md", "beta.md", "zeta.md"]) writeFileSync(join(directory, name), content);
  return { root, stateRoot: join(root, ".state", "episodes") };
}

test("episode store is append-only, revision-guarded and hash-chain verified", t => {
  const { stateRoot } = fixture(t);
  let tick = 0;
  const store = createEpisodeStore({ root: stateRoot, idFactory: () => "ep_1111111111111111", now: () => `2026-10-25T00:00:0${tick++}.000Z` });
  const created = store.create({ objective: "bounded attention" });
  assert.equal(created.revision, 1);
  const appended = store.append(created.episodeId, "episode.frozen", { frozen: true }, { expectedRevision: 1 });
  assert.equal(appended.revision, 2);
  assert.throws(() => store.append(created.episodeId, "episode.unfrozen", { frozen: false }, { expectedRevision: 1 }), /revision conflict/iu);
  const path = appended.path;
  const lines = readFileSync(path, "utf8").trimEnd().split("\n");
  const tampered = JSON.parse(lines[1]);
  tampered.payload.frozen = false;
  lines[1] = JSON.stringify(tampered);
  writeFileSync(path, `${lines.join("\n")}\n`);
  assert.throws(() => store.load(created.episodeId), /integrity verification/iu);
});
test("contribution inbox coordinates claims, dependencies, disposition and downstream impact without admission", t => {
  const { stateRoot } = fixture(t);
  const store = createContributionStore({ root: join(stateRoot, "..", "contributions"), idFactory: () => "contrib_1111111111111111", now: () => "2026-10-27T00:00:00.000Z" });
  const submitted = store.submit({ type: "retrieval-miss", objective: "bounded attention", profile: "audit", contributor: "fixture-agent", expected: "alpha", observed: "beta", narrowConclusion: "alpha was omitted", nextTest: "repeat", sourcePaths: [], dependsOn: ["BEACON-002"] });
  assert.equal(submitted.disposition, "pending");
  assert.deepEqual(submitted.dependencies, ["BEACON-002"]);
  assert.match(submitted.headSha256, /^[0-9a-f]{64}$/u);
  const claimed = store.claim(submitted.contributionId, { actor: "fixture-reviewer" });
  assert.equal(claimed.claim.actor, "fixture-reviewer");
  assert.throws(() => store.claim(submitted.contributionId, { actor: "other-reviewer" }), /already claimed/iu);
  const released = store.release(submitted.contributionId, { actor: "fixture-reviewer" });
  assert.equal(released.claim, null);
  store.claim(submitted.contributionId, { actor: "fixture-reviewer" });
  const decided = store.decide(submitted.contributionId, { decision: "accept", actor: "fixture-reviewer", reason: "Valid inbox report." });
  assert.equal(decided.disposition, "accepted");
  assert.equal(decided.decision.admissionEffect, false);
  const impacted = store.recordImpact(submitted.contributionId, { kind: "test", actor: "fixture-reviewer", target: "tests/repository/example.test.mjs", receiptSha256: "a".repeat(64) });
  assert.equal(impacted.impacts.length, 1);
  assert.equal(impacted.impacts[0].admissionEffect, false);
  assert.deepEqual(impacted.attribution.impactActors, ["fixture-reviewer"]);
  assert.equal(store.list().length, 1);
  assert.throws(() => store.decide(submitted.contributionId, { decision: "reject" }), /already has a disposition/iu);
  assert.throws(() => store.recordImpact("contrib_2222222222222222", { kind: "test", actor: "fixture-reviewer", target: "missing" }), /does not exist/iu);
});
test("runtime executes plan, answer, proposed update, approval, monitoring and replay", t => {
  const { root, stateRoot } = fixture(t);
  const runtime = createObservatoryRuntime({ root, stateRoot, idFactory: () => "ep_2222222222222222" });
  let episode = runtime.createEpisode({ objective: "boundary response candidate", profile: "experiment" });
  assert.equal(episode.revision, 1);
  assert.equal(episode.authority.requiresApprovalForLearning, true);
  const planned = runtime.planTurn(episode.episodeId, { task: "boundary response candidate" });
  episode = planned.episode;
  assert.equal(planned.turn.plan.baseline.sources.length, 3);
  assert.equal(planned.turn.plan.controls.emptyStatePreservesBaseline, true);
  assert.ok(planned.turn.plan.candidateUniverse.length >= 3);
  assert.match(planned.turn.plan.candidateUniverseSha256, /^[0-9a-f]{64}$/u);
  assert.throws(() => runtime.planTurn(episode.episodeId, { task: "a different objective" }), /exactly match/iu);
  const source = planned.turn.plan.adaptive.sources[0];
  const answer = runtime.recordAnswer(episode.episodeId, {
    turnId: planned.turn.turnId,
    model: { name: "test-model", settings: { temperature: 0 } },
    prompt: "Assess the candidate.",
    answer: "The source is useful for this bounded task.",
    claims: [{ key: "candidate.utility", statement: "The source is useful for this bounded task.", verdict: "supported", sourcePaths: [source.path] }],
  });
  assert.match(answer.answer.receipt.receiptSha256, /^[0-9a-f]{64}$/u);
  const proposed = runtime.proposeUpdate(episode.episodeId, { observations: [{ type: "verification-pass", sourcePath: source.path, evidenceSha256: "a".repeat(64), turnId: planned.turn.turnId }] });
  assert.equal(proposed.episode.beliefState.sequence, 0, "proposal must not mutate active state");
  assert.equal(proposed.proposal.successorState.sequence, 1);
  episode = runtime.decideUpdate(episode.episodeId, proposed.proposal.proposalId, { decision: "approve", reason: "Fixture verification." });
  assert.equal(episode.beliefState.sequence, 1);
  assert.equal(episode.metrics.approvedUpdates, 1);
  assert.equal(episode.beliefState.evidenceFamilies.length, 1);
  assert.equal(episode.beliefState.evidenceFamilies[0].independenceClass, "same-run");
  assert.ok(episode.metrics.meanUtility > 0.5);
  const replayed = runtime.replay(episode.episodeId, { processVariance: 0.02, adaptiveWeight: 0.2 });
  assert.equal(replayed.episode.beliefState.stateSha256, episode.beliefState.stateSha256, "replay must not mutate the live state");
  assert.equal(replayed.replay.turnComparisons.length, 1);
  assert.equal(replayed.replay.turnComparisons[0].candidateUniverseSha256, planned.turn.plan.candidateUniverseSha256);
  const admittedSha256 = episode.governance.admittedHistory.find(item => item.sequence === 0).stateSha256;
  episode = runtime.rollback(episode.episodeId, { targetStateSha256: admittedSha256, reason: "Exercise reversible admission." });
  assert.equal(episode.beliefState.sequence, 0);
  assert.equal(episode.metrics.rollbacks, 1);
  const rollbackReplay = runtime.replay(episode.episodeId, {});
  assert.equal(rollbackReplay.replay.finalStateSha256, episode.beliefState.stateSha256, "replay must apply recorded rollback events");
  assert.throws(() => runtime.proposeUpdate(episode.episodeId, { observations: [{ type: "verification-pass", sourcePath: source.path, sourceVersionSha256: "f".repeat(64), evidenceSha256: "b".repeat(64), turnId: planned.turn.turnId }] }), /sourceVersionSha256/iu);
  assert.throws(() => runtime.proposeUpdate(episode.episodeId, { observations: [{ type: "verification-pass", sourcePath: source.path, evidenceSha256: "c".repeat(64) }] }), /recorded turn/iu);
  assert.throws(() => runtime.proposeUpdate(episode.episodeId, { observations: [{ type: "verification-pass", sourcePath: source.path, evidenceSha256: "d".repeat(64), turnId: planned.turn.turnId, independenceClass: "independent-verifier" }] }), /host-derived/iu);
  episode = runtime.setFrozen(episode.episodeId, true);
  assert.equal(episode.frozen, true);
  assert.throws(() => runtime.proposeUpdate(episode.episodeId, { observations: [{ type: "user-rating", sourcePath: source.path, value: 1 }] }), /frozen/iu);
  assert.throws(() => runtime.setControls(episode.episodeId, { adaptiveWeight: 0.1 }), /frozen/iu);
  assert.throws(() => runtime.rollback(episode.episodeId, { targetStateSha256: proposed.proposal.successorState.stateSha256 }), /frozen/iu);
  assert.equal(runtime.listEpisodes()[0].metrics.turns, 1);
});
test("one objective may preregister a bounded longitudinal task schedule without opening cross-objective transfer", t => {
  const { root, stateRoot } = fixture(t);
  const runtime = createObservatoryRuntime({ root, stateRoot, idFactory: () => "ep_3333333333333333" });
  const tasks = ["boundary response alpha", "boundary response beta"];
  let episode = runtime.createEpisode({ objective: "audit one bounded response family", taskSchedule: tasks, profile: "audit" });
  assert.deepEqual(episode.taskSchedule, tasks);
  assert.match(episode.governance.taskScheduleSha256, /^[0-9a-f]{64}$/u);
  const planned = runtime.planTurn(episode.episodeId, { task: tasks[0] });
  assert.equal(planned.turn.task, tasks[0]);
  assert.throws(() => runtime.planTurn(episode.episodeId, { task: "an undeclared neighbouring objective" }), /outside the preregistered/iu);
  assert.throws(() => runtime.createEpisode({ objective: "bad schedule", taskSchedule: ["same", "same"] }), /unique/iu);
});
test("local Observatory server exposes static UI and the episode API", async t => {
  const { root, stateRoot } = fixture(t);
  const running = await startObservatoryServer({ root, stateRoot, port: 0 });
  t.after(() => new Promise(resolve => running.server.close(resolve)));
  const health = await fetch(`${running.url}/api/health`).then(response => response.json());
  assert.equal(health.status, "ok");
  assert.equal(health.contributionBeacon, "/api/beacon");
  const beacon = await fetch(`${running.url}/api/beacon`).then(response => response.json());
  assert.equal(beacon.status, "live-local");
  assert.equal(beacon.authority.corpusPromotion, false);
  assert.equal(beacon.live.contributionsEndpoint, "/api/contributions");
  const contributionResponse = await fetch(`${running.url}/api/contributions`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ type: "retrieval-miss", objective: "boundary response candidate", profile: "audit", contributor: "fixture-agent", expected: "alpha should be selected", observed: "alpha was omitted", narrowConclusion: "one bounded retrieval miss", nextTest: "repeat against the same corpus identity", sourcePaths: ["corpus/programmes/alpha.md"], dependsOn: ["BEACON-002"] }) });
  assert.equal(contributionResponse.status, 201);
  const contribution = await contributionResponse.json();
  assert.equal(contribution.disposition, "pending");
  assert.equal(contribution.authority.admissionEffect, false);
  const inbox = await fetch(`${running.url}/api/contributions`).then(response => response.json());
  assert.equal(inbox.contributions.length, 1);
  const claimResponse = await fetch(`${running.url}/api/contributions/${contribution.contributionId}/claim`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ actor: "fixture-reviewer" }) });
  assert.equal(claimResponse.status, 200);
  assert.equal((await claimResponse.json()).claim.actor, "fixture-reviewer");
  const dispositionResponse = await fetch(`${running.url}/api/contributions/${contribution.contributionId}/decision`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ decision: "reject", actor: "fixture-reviewer", reason: "Fixture disposition." }) });
  assert.equal(dispositionResponse.status, 200);
  assert.equal((await dispositionResponse.json()).disposition, "rejected");
  const impactResponse = await fetch(`${running.url}/api/contributions/${contribution.contributionId}/impact`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ kind: "no-change", actor: "fixture-reviewer", target: "bounded fixture review" }) });
  assert.equal(impactResponse.status, 200);
  assert.equal((await impactResponse.json()).impacts.length, 1);
  const page = await fetch(running.url);
  assert.equal(page.status, 200);
  assert.match(await page.text(), /Context Hub Observatory/iu);
  const createdResponse = await fetch(`${running.url}/api/episodes`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ objective: "boundary response candidate", profile: "audit" }) });
  assert.equal(createdResponse.status, 201);
  const created = await createdResponse.json();
  const listed = await fetch(`${running.url}/api/episodes`).then(response => response.json());
  assert.equal(listed.episodes[0].episodeId, created.episodeId);
  const plannedResponse = await fetch(`${running.url}/api/episodes/${created.episodeId}/turns`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ task: "boundary response candidate" }) });
  assert.equal(plannedResponse.status, 201);
  const planned = await plannedResponse.json();
  assert.equal(planned.episode.metrics.turns, 1);
  assert.equal(planned.episode.authority.corpusPromotion, false);
});
test("operator identity protects episode and contribution coordination writes while intake stays open", async t => {
  const { root, stateRoot } = fixture(t);
  const operatorToken = "fixture-operator-token";
  const running = await startObservatoryServer({ root, stateRoot, port: 0, operatorToken, operatorId: "fixture.operator" });
  t.after(() => new Promise(resolve => running.server.close(resolve)));
  const health = await fetch(`${running.url}/api/health`).then(response => response.json());
  assert.deepEqual({ id: health.operator.id, writeProtected: health.operator.writeProtected }, { id: "fixture.operator", writeProtected: true });
  assert.match(health.operator.credentialSha256, /^[0-9a-f]{64}$/u);
  const proposal = await fetch(`${running.url}/api/contributions`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ type: "retrieval-miss", objective: "boundary response candidate", profile: "audit", contributor: "fixture-agent", expected: "alpha", observed: "beta", narrowConclusion: "bounded miss", nextTest: "repeat", sourcePaths: [] }) });
  assert.equal(proposal.status, 201, "proposal intake must not require operator authority");
  const contribution = await proposal.json();
  const deniedClaim = await fetch(`${running.url}/api/contributions/${contribution.contributionId}/claim`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ actor: "fixture-reviewer" }) });
  assert.equal(deniedClaim.status, 401);
  const deniedEpisode = await fetch(`${running.url}/api/episodes`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ objective: "boundary response candidate", profile: "audit" }) });
  assert.equal(deniedEpisode.status, 401);
  const authorisedEpisode = await fetch(`${running.url}/api/episodes`, { method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${operatorToken}` }, body: JSON.stringify({ objective: "boundary response candidate", profile: "audit" }) });
  assert.equal(authorisedEpisode.status, 201);
  const authorisedClaim = await fetch(`${running.url}/api/contributions/${contribution.contributionId}/claim`, { method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${operatorToken}` }, body: JSON.stringify({ actor: "fixture-reviewer" }) });
  assert.equal(authorisedClaim.status, 200);
});
